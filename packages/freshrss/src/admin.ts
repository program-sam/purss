import { execFile } from "node:child_process";
import { EngineError } from "./errors.ts";
import { redactText } from "./redact.ts";

/**
 * Fixed engine administration operations, run inside the engine container through a configurable command
 * prefix (`PURSS_ENGINE_EXEC`, default `podman exec --user www-data purss-freshrss`). Every operation is a
 * constant program plus structured arguments handed to `execFile`: there is no shell, and no caller text is
 * ever interpreted as a command. Nothing here touches the engine's database: the operations are FreshRSS's own
 * CLI scripts plus three fixed `php -r` snippets (identity hash, archiving read, egress proxy and fetch-cache keys in config.php).
 */


/**
 * The shortest time (seconds) the engine keeps a fetched feed in its cache, whatever the feed's own `Cache-Control` says
 * (`limits.cache_duration_min`; the engine's default is 60). Every account has its own engine user, but the cache is shared:
 * its key is the feed address plus the fetch options, so a feed that sends `no-cache` or `no-store` is fetched again for
 * each user within one refresh run unless it is kept at least as long as the run. Refreshes happen every 15 minutes (900 s),
 * so holding a fetch for 800 s makes the users' refreshes of one feed share a single request without anything going stale.
 */
export const ENGINE_FETCH_CACHE_MIN_SECONDS = 800;

/**
 * The only inline PHP the admin operations run. Exported so the engine image's HTTP helper can allow
 * exactly these (by hash) and nothing else; `infra/engine/image/allowlist.json` is checked against them.
 */
export const ADMIN_SNIPPETS = {
  identity:
    'echo hash("sha256", "purss-engine-identity:1:" . (require rtrim(getenv("DATA_PATH") ?: "/var/www/FreshRSS/data", "/") . "/config.php")["salt"]);',
  archiving:
    '$c = require rtrim(getenv("DATA_PATH") ?: "/var/www/FreshRSS/data", "/") . "/users/" . $argv[1] . "/config.php"; echo json_encode(["archiving" => $c["archiving"] ?? null, "ttl_default" => $c["ttl_default"] ?? null]);',
  egress:
    '$p = rtrim(getenv("DATA_PATH") ?: "/var/www/FreshRSS/data", "/") . "/config.php"; $c = require $p; $proxy = $argv[1]; ' +
      '$want = [CURLOPT_PROXYTYPE => CURLPROXY_HTTP, CURLOPT_PROXY => $proxy]; ' +
      `if (($c["curl_options"] ?? null) === $want && ($c["internal_host_allowlist"] ?? null) === [$proxy] && ($c["limits"]["cache_duration_min"] ?? null) === ${ENGINE_FETCH_CACHE_MIN_SECONDS}) { echo "unchanged"; exit(0); } ` +
      `if ($argv[2] === "apply") { $c["curl_options"] = $want; $c["internal_host_allowlist"] = [$proxy]; $c["limits"]["cache_duration_min"] = ${ENGINE_FETCH_CACHE_MIN_SECONDS}; $t = $p . ".tmp"; ` +
      'if (file_put_contents($t, "<?php\n return " . var_export($c, true) . ";\n") === false || !rename($t, $p)) { exit(1); } } echo "updated";',
} as const;

/** FreshRSS CLI scripts the admin operations call (with structured arguments only). */
export const ADMIN_CLI_SCRIPTS = ["create-user.php", "update-user.php", "list-users.php", "actualize-user.php", "delete-user.php"] as const;

/**
 * Runs the fixed operations through the engine image's admin helper over HTTP (Compose), instead of
 * `podman exec`. Same command arrays; the helper refuses anything outside the allowlist.
 */
export function httpExecRunner(url: string, token: string, fetchImpl: typeof fetch = fetch): ExecRunner {
  return async (file, args, opts) => {
    let res: Response;
    try {
      res = await fetchImpl(url, {
        method: "POST",
        headers: { "content-type": "application/json", authorization: `Bearer ${token}` },
        body: JSON.stringify({ command: [file, ...args] }),
        signal: opts.signal ? AbortSignal.any([opts.signal, AbortSignal.timeout(opts.timeoutMs)]) : AbortSignal.timeout(opts.timeoutMs),
        redirect: "error",
      });
    } catch (e) {
      if (opts.signal?.aborted) throw new ExecStartError("aborted");
      if (e instanceof Error && e.name === "TimeoutError") throw new ExecStartError("timeout");
      throw new ExecStartError("spawn");
    }
    if (!res.ok) throw new ExecStartError("spawn");
    const out = (await res.json()) as Partial<ExecResult>;
    if (typeof out.exitCode !== "number") throw new ExecStartError("spawn");
    return { exitCode: out.exitCode, stdout: String(out.stdout ?? ""), stderr: String(out.stderr ?? "") };
  };
}

export const DEFAULT_ENGINE_EXEC = "podman exec --user www-data purss-freshrss";

/** Same alphabet FreshRSS accepts, minus a leading dash that its option parser could mistake for a flag. */
const USERNAME = /^[0-9A-Za-z_.@][0-9A-Za-z_.@-]{0,127}$/;
/** API passwords are generated by us; the strict alphabet keeps them safe as one CLI argument. */
const API_PASSWORD = /^[0-9A-Za-z._~]{16,128}$/;

export function isValidEngineUsername(name: string): boolean {
  return USERNAME.test(name);
}
export function isValidApiPassword(pw: string): boolean {
  return API_PASSWORD.test(pw);
}

/** Parses `PURSS_ENGINE_EXEC`: a JSON array of strings, or whitespace-separated words (no quoting, no shell). */
export function parseExecPrefix(value: string | undefined): string[] {
  const raw = (value ?? DEFAULT_ENGINE_EXEC).trim();
  let words: string[];
  if (raw.startsWith("[")) {
    let parsed: unknown;
    try {
      parsed = JSON.parse(raw);
    } catch {
      throw new EngineError("exec", "PURSS_ENGINE_EXEC looks like JSON but is not valid.", { retryable: false });
    }
    if (!Array.isArray(parsed) || !parsed.every((w) => typeof w === "string")) {
      throw new EngineError("exec", "PURSS_ENGINE_EXEC must be a JSON array of strings.", { retryable: false });
    }
    words = parsed as string[];
  } else {
    words = raw.split(/\s+/).filter(Boolean);
  }
  if (words.length === 0 || words.some((w) => w.includes("\0"))) throw new EngineError("exec", "PURSS_ENGINE_EXEC is empty or invalid.", { retryable: false });
  return words;
}

export type ExecResult = { exitCode: number; stdout: string; stderr: string };
export type ExecRunner = (
  file: string,
  args: readonly string[],
  opts: { timeoutMs: number; signal?: AbortSignal; env?: Record<string, string> },
) => Promise<ExecResult>;

/** Failure to run a command at all. Never carries the command line (it can contain passwords). */
export class ExecStartError extends Error {
  readonly reason: "timeout" | "aborted" | "spawn";
  constructor(reason: "timeout" | "aborted" | "spawn") {
    super(`exec ${reason}`);
    this.name = "ExecStartError";
    this.reason = reason;
  }
}

export const nodeExec: ExecRunner = (file, args, opts) =>
  new Promise((resolve, reject) => {
    const child = execFile(file, [...args], { timeout: opts.timeoutMs, maxBuffer: 8 * 1024 * 1024, signal: opts.signal, encoding: "utf8", env: opts.env ? { ...process.env, ...opts.env } : undefined }, (error, stdout, stderr) => {
      if (!error) return resolve({ exitCode: 0, stdout, stderr });
      const e = error as NodeJS.ErrnoException & { killed?: boolean };
      if (typeof e.code === "number") return resolve({ exitCode: e.code, stdout, stderr });
      if (opts.signal?.aborted || e.name === "AbortError") return reject(new ExecStartError("aborted"));
      if (e.killed) return reject(new ExecStartError("timeout"));
      reject(new ExecStartError("spawn"));
    });
    child.stdin?.end();
  });

export type EngineAdminOptions = {
  /** Command prefix words, e.g. from {@link parseExecPrefix}. */
  prefix: readonly string[];
  run?: ExecRunner;
  timeoutMs?: number;
  signal?: AbortSignal;
};

const ALREADY_EXISTS = 3; // FreshRSS cli EXIT_CODE_ALREADY_EXISTS

export class EngineAdmin {
  readonly #prefix: readonly string[];
  readonly #run: ExecRunner;
  readonly #timeout: number;
  readonly #signal: AbortSignal | undefined;

  constructor(opts: EngineAdminOptions) {
    if (opts.prefix.length === 0 && !opts.run) throw new EngineError("exec", "The engine command prefix is empty.", { retryable: false });
    this.#prefix = opts.prefix;
    this.#run = opts.run ?? nodeExec;
    this.#timeout = opts.timeoutMs ?? 120_000;
    this.#signal = opts.signal;
  }

  /** `PURSS_ENGINE_ADMIN_URL` (+ token) selects the engine image's HTTP helper; otherwise `PURSS_ENGINE_EXEC`. */
  static fromEnv(env: NodeJS.ProcessEnv = process.env, extra: Omit<EngineAdminOptions, "prefix"> & { adminToken?: string } = {}): EngineAdmin {
    const { adminToken, ...rest } = extra;
    if (env.PURSS_ENGINE_ADMIN_URL) {
      if (!adminToken) throw new EngineError("exec", "PURSS_ENGINE_ADMIN_URL needs the service token.", { retryable: false });
      return new EngineAdmin({ prefix: [], run: httpExecRunner(env.PURSS_ENGINE_ADMIN_URL, adminToken), ...rest });
    }
    return new EngineAdmin({ prefix: parseExecPrefix(env.PURSS_ENGINE_EXEC), ...rest });
  }

  /** Creates an API-only engine user (no web password, no default feeds). Returns false when it already exists. */
  async createUser(input: { username: string; apiPassword: string }): Promise<{ created: boolean }> {
    checkUser(input.username);
    checkApiPassword(input.apiPassword);
    const r = await this.#cli("create-user.php", ["--no-default-feeds", `--user=${input.username}`, `--api-password=${input.apiPassword}`]);
    if (r.exitCode === 0) return { created: true };
    if (r.exitCode === ALREADY_EXISTS) return { created: false };
    throw this.#failure("create the engine user", r, [input.apiPassword]);
  }

  async setApiPassword(input: { username: string; apiPassword: string }): Promise<void> {
    checkUser(input.username);
    checkApiPassword(input.apiPassword);
    const r = await this.#cli("update-user.php", [`--user=${input.username}`, `--api-password=${input.apiPassword}`]);
    if (r.exitCode !== 0) throw this.#failure("set the engine user's API password", r, [input.apiPassword]);
  }

  /** Creates the user or, when it exists, (re)sets its API password: one idempotent provisioning step. */
  async ensureUser(input: { username: string; apiPassword: string }): Promise<{ created: boolean }> {
    const { created } = await this.createUser(input);
    if (!created) await this.setApiPassword(input);
    return { created };
  }

  /** Deletes an engine user with its data directory. FreshRSS exits 1 for an unknown user, so callers check first. */
  async deleteUser(username: string): Promise<void> {
    checkUser(username);
    const r = await this.#cli("delete-user.php", [`--user=${username}`]);
    if (r.exitCode !== 0) throw this.#failure("delete the engine user", r);
  }

  async listUsers(): Promise<string[]> {
    const r = await this.#cli("list-users.php", []);
    if (r.exitCode !== 0) throw this.#failure("list engine users", r);
    return r.stdout.split("\n").map((l) => l.trim()).filter(Boolean);
  }

  async userExists(username: string): Promise<boolean> {
    checkUser(username);
    return (await this.listUsers()).some((u) => u.toLowerCase() === username.toLowerCase());
  }

  /**
   * Refreshes feeds now. FreshRSS exits 1 when no feed needed updating, which is not an error; real failures
   * (missing user, bad feed id) carry a message on stderr.
   */
  async actualize(input: { username: string; feedId?: number }): Promise<{ feeds: number; newArticles: number }> {
    checkUser(input.username);
    const args = [`--user=${input.username}`];
    if (input.feedId !== undefined) {
      if (!Number.isInteger(input.feedId) || input.feedId < 1) throw new EngineError("exec", "The feed id must be a positive integer.", { retryable: false });
      args.push(`--feed-id=${input.feedId}`);
    }
    const r = await this.#cli("actualize-user.php", args);
    const m = /actualized (\d+) feeds? for .* \((\d+) new articles?\)/.exec(r.stdout);
    if (m) return { feeds: Number(m[1]), newArticles: Number(m[2]) };
    if (r.exitCode === 0 || r.exitCode === 1) return { feeds: 0, newArticles: 0 };
    throw this.#failure("refresh the engine user's feeds", r);
  }

  /**
   * Stable identity of this engine instance: a hash of the instance salt that FreshRSS generates once at
   * install time. It survives restarts, upgrades and a restore of the same data directory, and changes for a
   * fresh install, which is what "replacement engine" means. The salt itself never leaves the container.
   */
  async engineIdentity(): Promise<string> {
    const r = await this.#exec(["php", "-r", ADMIN_SNIPPETS.identity]);
    const hex = r.stdout.trim();
    if (r.exitCode !== 0 || !/^[0-9a-f]{64}$/.test(hex)) throw this.#failure("read the engine identity", r);
    return `freshrss:${hex.slice(0, 32)}`;
  }

  /** Engine's effective archiving limits for one user (read-only), for recording and health warnings. */
  async readUserArchiving(username: string): Promise<Record<string, unknown>> {
    checkUser(username);
    const r = await this.#exec(["php", "-r", ADMIN_SNIPPETS.archiving, username]);
    if (r.exitCode !== 0) throw this.#failure("read the engine user's archiving limits", r);
    try {
      return JSON.parse(r.stdout) as Record<string, unknown>;
    } catch {
      throw new EngineError("protocol", "The engine's archiving settings could not be read.");
    }
  }

  /**
   * Makes the engine's system config use exactly one outbound HTTP proxy, allow only that proxy's address as an
   * internal host, and keep every fetched feed in its shared cache for at least `ENGINE_FETCH_CACHE_MIN_SECONDS` (the
   * engine's other `limits` keep their defaults). Applied in place to `data/config.php` (the file FreshRSS itself writes),
   * so changing the proxy never needs a new volume. With `dryRun` nothing is written; "updated" then means "would change".
   */
  async applyEgressConfig(input: { proxyHostPort: string; dryRun?: boolean }): Promise<"unchanged" | "updated"> {
    if (!/^\d{1,3}(\.\d{1,3}){3}:\d{1,5}$/.test(input.proxyHostPort)) throw new EngineError("exec", "The egress proxy must be an IPv4 address and port.", { retryable: false });
    const r = await this.#exec(["php", "-r", ADMIN_SNIPPETS.egress, input.proxyHostPort, input.dryRun ? "dry" : "apply"]);
    const out = r.stdout.trim();
    if (r.exitCode !== 0 || (out !== "unchanged" && out !== "updated")) throw this.#failure("apply the egress proxy configuration", r);
    return out;
  }

  async #cli(script: string, args: readonly string[]): Promise<ExecResult> {
    return this.#exec(["php", "-f", `./cli/${script}`, "--", ...args]);
  }

  async #exec(command: readonly string[]): Promise<ExecResult> {
    const [file, ...rest] = [...this.#prefix, ...command];
    try {
      return await this.#run(file!, rest, { timeoutMs: this.#timeout, signal: this.#signal });
    } catch (e) {
      if (this.#signal?.aborted || (e instanceof ExecStartError && e.reason === "aborted")) throw new EngineError("cancelled", "The engine command was cancelled.");
      if (e instanceof ExecStartError && e.reason === "timeout") throw new EngineError("timeout", "The engine command did not finish in time.");
      // Never forward the raw error: runtime errors echo the full command line, which contains passwords.
      throw new EngineError("exec", "The engine command could not be started. Is the engine container running?");
    }
  }

  #failure(what: string, r: ExecResult, secrets: readonly string[] = []): EngineError {
    const detail = redactText(`${r.stderr}\n${r.stdout}`.trim().split("\n").filter(Boolean).slice(-2).join(" | "), secrets);
    return new EngineError("exec", `The engine could not ${what} (exit ${r.exitCode})${detail ? `: ${detail}` : "."}`, { retryable: r.exitCode !== 2 });
  }
}

function checkUser(name: string): void {
  if (!USERNAME.test(name)) throw new EngineError("exec", "The engine username is not valid.", { retryable: false });
}
function checkApiPassword(pw: string): void {
  if (!API_PASSWORD.test(pw)) throw new EngineError("exec", "The engine API password does not meet the required format.", { retryable: false });
}
