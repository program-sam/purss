// Writes the native shells' text files from packages/translations/src/en/native.ts: the Android app's string resources, the iOS
// widgets' and notification extension's Swift (and the App Intent names in PanelChoice.swift), and the desktop app's
// Rust module. Edit the catalog, then run this (npm run translations:native); a test fails when a file is out
// of date. Usage: node scripts/native-translations.ts
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { native } from "@purss/translations/native";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ANDROID_VALUES = "apps/mobile/android/app/src/main/res/values";
const RUST_COPY = "apps/desktop/src-tauri/src/translations.rs";
const IOS_APP = "apps/mobile/ios/App";
const SWIFT_COPY = `${IOS_APP}/Widgets/NativeTranslations.swift`;
const PANEL_CHOICE = `${IOS_APP}/Widgets/PanelChoice.swift`;
const NOTE = "Generated by scripts/native-translations.ts. Edit packages/translations/src/en/native.ts and run `npm run translations:native`.";

type Tree = { [key: string]: string | Tree };
export type Generated = { file: string; text: string };

const PLACEHOLDER = /\{([a-z][a-z0-9]*)\}/g;

/** The names of the values a text takes, in the order they first appear. */
export function placeholders(text: string): string[] {
  const names = [...text.matchAll(PLACEHOLDER)].map((m) => m[1]!);
  const rest = text.replace(PLACEHOLDER, "");
  if (/[{}]/.test(rest)) throw new Error(`"${text}": a brace that isn't a {name} of lower-case letters and digits`);
  return [...new Set(names)];
}

const snake = (key: string) => key.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();

/** Every text with the path of keys that leads to it. */
function leaves(tree: Tree, path: string[] = []): { path: string[]; text: string }[] {
  return Object.entries(tree).flatMap(([key, value]) =>
    typeof value === "string" ? [{ path: [...path, key], text: value }] : leaves(value, [...path, key]));
}

function checkKey(key: string): void {
  if (!/^[a-z][a-zA-Z0-9]*$/.test(key)) throw new Error(`"${key}": catalog keys are camelCase words`);
}

// ---- Android ---------------------------------------------------------------------------------------------------

/** An Android string resource's text: `{name}` becomes the positional `%1$s`, and what XML and aapt read specially is escaped. */
export function androidText(text: string): string {
  if (text.includes("%")) throw new Error(`"${text}": a % has no place in an Android string`);
  const names = placeholders(text);
  return text
    .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/"/g, "\\\"").replace(/\n/g, "\\n")
    .replace(/^([@?])/, "\\$1")
    .replace(PLACEHOLDER, (_, name: string) => `%${names.indexOf(name) + 1}$s`);
}

function androidFile(tree: Tree): string {
  const seen = new Map<string, string>();
  const lines = leaves(tree).map(({ path: keys, text }) => {
    keys.forEach(checkKey);
    const name = keys.map(snake).join("_");
    const was = seen.get(name);
    if (was) throw new Error(`${keys.join(".")} and ${was} are both the Android string ${name}`);
    seen.set(name, keys.join("."));
    return `    <string name="${name}">${androidText(text)}</string>`;
  });
  return [`<?xml version="1.0" encoding="utf-8"?>`, `<!-- ${NOTE} -->`, "<resources>", ...lines, "</resources>", ""].join("\n");
}

// ---- Rust ------------------------------------------------------------------------------------------------------

const RUST_KEYWORDS = new Set(["as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum", "extern", "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "self", "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where", "while"]);

function rustString(text: string): string {
  return `"${text.replace(/\\/g, "\\\\").replace(/"/g, "\\\"").replace(/\n/g, "\\n")}"`;
}

function rustItems(tree: Tree, depth: number, trail: string[]): string[] {
  const pad = "    ".repeat(depth);
  return Object.entries(tree).flatMap(([key, value]) => {
    checkKey(key);
    const name = snake(key);
    if (RUST_KEYWORDS.has(name)) throw new Error(`${[...trail, key].join(".")}: ${name} is a Rust keyword`);
    if (typeof value !== "string") return [`${pad}pub mod ${name} {`, ...rustItems(value, depth + 1, [...trail, key]), `${pad}}`];
    const names = placeholders(value);
    for (const n of names) if (RUST_KEYWORDS.has(n)) throw new Error(`${[...trail, key].join(".")}: {${n}} is a Rust keyword`);
    if (names.length === 0) return [`${pad}pub const ${name.toUpperCase()}: &str = ${rustString(value)};`];
    return [
      `${pad}pub fn ${name}(${names.map((n) => `${n}: impl std::fmt::Display`).join(", ")}) -> String {`,
      `${pad}    format!(${rustString(value)})`,
      `${pad}}`,
    ];
  });
}

function rustFile(tree: Tree): string {
  return [`// ${NOTE}`, "// Some texts are used on one system only.", "#![allow(dead_code)]", "", ...rustItems(tree, 0, []), ""].join("\n");
}

// ---- Swift -----------------------------------------------------------------------------------------------------

const SWIFT_KEYWORDS = new Set(["associatedtype", "class", "deinit", "enum", "extension", "fileprivate", "func", "import", "init", "inout", "internal", "let", "open", "operator", "private", "precedencegroup", "protocol", "public", "rethrows", "static", "struct", "subscript", "typealias", "var", "break", "case", "catch", "continue", "default", "defer", "do", "else", "fallthrough", "for", "guard", "if", "in", "repeat", "return", "throw", "switch", "where", "while", "as", "false", "is", "nil", "self", "super", "throws", "true", "try", "some", "any", "Type", "Any", "Self"]);

/** A Swift string literal: `{name}` becomes `\\(name)` when `values` is set. */
export function swiftString(text: string, values = false): string {
  const escaped = text.replace(/\\/g, "\\\\").replace(/"/g, "\\\"").replace(/\n/g, "\\n");
  return `"${values ? escaped.replace(PLACEHOLDER, (_, name: string) => `\\(${name})`) : escaped}"`;
}

/** A name Swift takes as it is, a keyword in backticks (`open`), which callers still write plainly after a dot. */
const swiftName = (key: string) => (SWIFT_KEYWORDS.has(key) ? `\`${key}\`` : key);

function swiftItems(tree: Tree, depth: number, trail: string[]): string[] {
  const pad = "    ".repeat(depth);
  return Object.entries(tree).flatMap(([key, value]) => {
    checkKey(key);
    const where = [...trail, key].join(".");
    if (typeof value !== "string") return [`${pad}enum ${key[0]!.toUpperCase()}${key.slice(1)} {`, ...swiftItems(value, depth + 1, [...trail, key]), `${pad}}`];
    const names = placeholders(value);
    for (const n of names) if (SWIFT_KEYWORDS.has(n)) throw new Error(`${where}: {${n}} is a Swift keyword`);
    if (names.length === 0) return [`${pad}static let ${swiftName(key)} = ${swiftString(value)}`];
    return [`${pad}static func ${swiftName(key)}(${names.map((n) => `${n}: any CustomStringConvertible`).join(", ")}) -> String { ${swiftString(value, true)} }`];
  });
}

function swiftFile(tree: Tree): string {
  return [`// ${NOTE}`, "// A plain text is a constant (NativeTranslations.Widget.loading), a text with values a function (NativeTranslations.Widget.pausedAt(time:)).", "", "enum NativeTranslations {", ...swiftItems(tree, 1, []), "}", ""].join("\n");
}

/** A text of the catalog by its dotted path (`ios.panelChoice.source`). */
function textAt(tree: Tree, dotted: string): string {
  const value = dotted.split(".").reduce<string | Tree | undefined>((t, k) => (t && typeof t !== "string" ? t[k] : undefined), tree);
  if (typeof value !== "string") throw new Error(`${dotted}: no such text in packages/translations/src/en/native.ts`);
  if (placeholders(value).length) throw new Error(`${dotted}: a text written into Swift source takes no values`);
  return value;
}

/**
 * A Swift file whose lines that end in `// translation: <path>` carry that catalog text as their one string literal: for text
 * Xcode reads at build time (App Intent names), which has to be written out where it is used.
 */
export function syncMarkedLiterals(source: string, tree: Tree, file: string): string {
  return source.split("\n").map((line) => {
    const m = /^(.*?)"(?:[^"\\]|\\.)*"(.*\/\/ translation: ([a-zA-Z.]+))$/.exec(line);
    if (!m) {
      if (line.includes("// translation:")) throw new Error(`${file}: a "// translation:" line needs one string literal before it: ${line.trim()}`);
      return line;
    }
    return `${m[1]}${swiftString(textAt(tree, m[3]!))}${m[2]}`;
  }).join("\n");
}

// ---- Files -----------------------------------------------------------------------------------------------------

/** Every generated file with the text it should hold. */
export function generate(): Generated[] {
  const { widgetPreview, ...strings } = native.android;
  return [
    { file: `${ANDROID_VALUES}/strings.xml`, text: androidFile(strings) },
    { file: `${ANDROID_VALUES}/widget_strings.xml`, text: androidFile({ widget: native.widget, widgetPreview }) },
    { file: SWIFT_COPY, text: swiftFile({ widget: native.widget, ios: native.ios }) },
    { file: PANEL_CHOICE, text: syncMarkedLiterals(readFileSync(path.join(root, PANEL_CHOICE), "utf8"), native, PANEL_CHOICE) },
    { file: RUST_COPY, text: rustFile(native.desktop) },
  ];
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const { file, text } of generate()) {
    const target = path.join(root, file);
    let current = "";
    try { current = readFileSync(target, "utf8"); } catch { /* a new file */ }
    if (current === text) continue;
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, text);
    console.log(`wrote ${file}`);
  }
}
